import type { Ingredient, ShoppingCategory, Unit } from '../types';

/** Atalho para declarar um ingrediente prescrito. */
export function ing(
  key: string,
  text: string,
  category: ShoppingCategory,
  qty?: number,
  unit?: Unit,
  extra: Partial<Ingredient> = {},
): Ingredient {
  return { key, text, category, ...(qty !== undefined ? { qty } : {}), ...(unit ? { unit } : {}), ...extra };
}

/** Ingrediente "a gosto"/"à vontade": aparece na lista de compras sem quantidade. */
export function free(key: string, text: string, category: ShoppingCategory, extra: Partial<Ingredient> = {}): Ingredient {
  return { key, text, category, free: true, ...extra };
}

